export function trainingCopy(lang: Lang, flags: { trainingStage?: string; trainingPriority?: string }): string | null {
  const L = TRAINING_LABEL[lang];
  if (flags.trainingStage === "trained" && flags.trainingPriority === "active") return L.active;
  if (flags.trainingStage && L[flags.trainingStage]) return L[flags.trainingStage];
  if (flags.trainingPriority && L[flags.trainingPriority]) return L[flags.trainingPriority];
  return null;
}
